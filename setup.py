"""Build hook: ship the precompiled TS bundle + schema inside the installed package.

The wheel must be able to run ``engine="ts"`` from a clean install (no source
tree, no node_modules). This copies the built ``release/`` artifacts into
``python/astra_bridge/release/`` inside the wheel; ``agent_runtime._default_script``
prefers that packaged copy. Generated by the real build, never hand-copied.
"""
from pathlib import Path

from setuptools import setup
from setuptools.command.build_py import build_py as _build_py


class build_py(_build_py):
    def run(self):
        super().run()
        source = Path(__file__).resolve().parent / "release"
        target = Path(self.build_lib) / "python" / "astra_bridge" / "release"
        if source.is_dir():
            for path in source.rglob("*"):
                if path.is_file():
                    destination = target / path.relative_to(source)
                    self.mkpath(str(destination.parent))
                    destination.write_bytes(path.read_bytes())


setup(cmdclass={"build_py": build_py})
