def odd_part_evidence(n: int) -> Evidence:
    """odd_part(n) = n / 2^v2(n), as Evidence.

    Self-check: independent re-factorization — the reported value m must be
    odd and satisfy n == m * 2^k for the recomputed 2-adic valuation k.
    """
    value = odd_part(n)
    m, k = n, 0
    while m % 2 == 0:
        m //= 2
        k += 1
    ok = m == value and m % 2 == 1 and m * 2**k == n
    return Evidence(
        value=value,
        certificate=f"factorization witness: n = {value} * 2^{k}",
        self_check=f"re-factorization n == odd * 2^k: {'ok' if ok else 'MISMATCH'}",
        feasibility="ok",
        complexity_bound="O(log n)",
    )


def odd_part_table_evidence(limit: int, modulus: int = 4) -> Evidence:
    """odd_part(n) mod m for n = 1..limit, as Evidence.

    Self-check: every table entry is independently re-derived from the
    factored form n = m * 2^k (m odd) and compared against the table.
    """
    table = odd_part_table(limit, modulus)
    ok = True
    for n in range(1, limit + 1):
        m = n
        while m % 2 == 0:
            m //= 2
        if table[n - 1] != m % modulus:
            ok = False
            break
    return Evidence(
        value=table,
        certificate=f"window 1..{limit} mod {modulus}",
        self_check=f"per-entry re-factorization scan: {'ok' if ok else 'MISMATCH'}",
        feasibility="ok",
        complexity_bound=f"O(limit * log) = O({limit})",
    )
