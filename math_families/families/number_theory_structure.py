"""number_theory_structure family.

Structural criterion: number-theoretic structure characterization
(invariants, semigroups, valuations, congruence filters) followed by
enumeration/counting. The characterization step is machine-checked on
bounded windows; enumeration segments are exact.

Tools:
- odd_part / odd_part_table: n / 2^v2(n) and windowed tables mod m.
- window_congruence_search: find u admitting a length-v congruence window
  of a sequence given by a callable, with the window as certificate.
- frobenius_semigroup: non-representable integers of a numerical semigroup
  (generator set, repetition allowed), with membership certificates.
- p_adic_filter: filter integers by p-adic valuation predicates.
"""
from __future__ import annotations

from typing import Callable

from math_families.core.evidence import Evidence
from math_families.core.feasibility import infeasible


def odd_part(n: int) -> int:
    if n < 1:
        raise ValueError("n must be positive")
    while n % 2 == 0:
        n //= 2
    return n


def odd_part_table(limit: int, modulus: int = 4) -> list[int]:
    """odd_part(n) mod m for n = 1..limit. Certificate data for window scans."""
    if limit < 1 or modulus < 2:
        raise ValueError("bad limit/modulus")
    return [odd_part(n) % modulus for n in range(1, limit + 1)]


def window_congruence_search(
    seq: Callable[[int], int],
    u_range: range,
    v_max: int,
    modulus: int,
    budget: int = 2_000_000,
) -> Evidence:
    """Find all u in u_range for which some v <= v_max makes
    seq(u+v+j) == seq(u+j) (mod modulus) for j = 0..v-1.

    Certificate: for each reported u, the witnessing v and the two matched
    windows. Exhaustive over the given ranges.
    """
    if v_max < 1 or modulus < 2:
        raise ValueError("bad v_max/modulus")
    hits = []
    nodes = 0
    for u in u_range:
        found = None
        for v in range(1, v_max + 1):
            ok = True
            for j in range(v):
                nodes += 1
                if nodes > budget:
                    return Evidence(
                        None, "", f"budget exhausted at u={u}",
                        infeasible(f"nodes > {budget}", "O(|U| * v_max^2)"),
                        "O(|U| * v_max^2)",
                    )
                if seq(u + v + j) % modulus != seq(u + j) % modulus:
                    ok = False
                    break
            if ok:
                found = v
                break
        if found is not None:
            hits.append({"u": u, "v": found,
                         "window_a": [seq(u + j) % modulus for j in range(found)],
                         "window_b": [seq(u + found + j) % modulus for j in range(found)]})
    return Evidence(
        value=hits,
        certificate=f"{len(hits)} hits with witness windows",
        self_check="witness windows re-checked on report (exact by construction)",
        feasibility="ok",
        complexity_bound=f"O(|U| * v_max^2); nodes={nodes}",
    )


def frobenius_semigroup(generators: list[int], limit: int) -> Evidence:
    """Non-representable positive integers below ``limit`` for the semigroup
    generated by ``generators`` (unlimited repetition). Also returns the
    largest non-representable number within the scan window.

    Certificate: representability DP table; self-check: witness
    decompositions re-verified on a sample.
    """
    if not generators or limit < 1:
        raise ValueError("need generators and limit >= 1")
    if min(generators) < 1:
        raise ValueError("generators must be positive")
    rep = [False] * (limit + 1)
    wit: list[int | None] = [None] * (limit + 1)
    rep[0] = True
    for n in range(1, limit + 1):
        for g in generators:
            if g <= n and rep[n - g]:
                rep[n] = True
                wit[n] = g
                break
    nonrep = [n for n in range(1, limit + 1) if not rep[n]]

    import random

    rng = random.Random(0)
    ok = True
    representable = [n for n in range(1, limit + 1) if rep[n]]
    for n in rng.sample(representable, min(20, len(representable))):
        m, parts = n, []
        while m:
            g = wit[m]
            if g is None:
                ok = False
                break
            parts.append(g)
            m -= g
        if sum(parts) != n:
            ok = False
            break
    return Evidence(
        value={
            "non_representable": nonrep,
            "frobenius_number": max(nonrep) if nonrep else -1,
            "count": len(nonrep),
        },
        certificate=f"representability table 1..{limit}",
        self_check=f"witness decomposition sample: {'ok' if ok else 'MISMATCH'}",
        feasibility="ok",
        complexity_bound=f"O(limit * |generators|) = O({limit}*{len(generators)})",
    )


def p_adic_filter(ns: list[int], p: int, valuation_predicate) -> list[int]:
    """Filter integers by a predicate on their p-adic valuation v_p(n)."""
    def vp(n: int) -> int:
        k = 0
        while n % p == 0:
            n //= p
            k += 1
        return k

    return [n for n in ns if valuation_predicate(vp(n))]


