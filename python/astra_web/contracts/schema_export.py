"""Astra Web 契约 - JSON Schema 导出脚本.

Usage:
    python -m python.astra_web.contracts.schema_export --out packages/web-contract/schema
    python -m python.astra_web.contracts.schema_export --check --out packages/web-contract/schema

`--check` never writes: it compares the generated bytes with the committed
schemas and exits non-zero on drift.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from python.astra_web.contracts.dto import (
    CapabilitiesDto,
    ErrorDto,
    MetricsDto,
    RunEventEnvelope,
    RunRequestDto,
    SolveResultDto,
    TraceRowDto,
)

SCHEMA_MODELS: dict[str, type[BaseModel]] = {
    "SolveResultDto": SolveResultDto,
    "TraceRowDto": TraceRowDto,
    "MetricsDto": MetricsDto,
    "RunEventEnvelope": RunEventEnvelope,
    "RunRequestDto": RunRequestDto,
    "CapabilitiesDto": CapabilitiesDto,
    "ErrorDto": ErrorDto,
}

SCHEMA_VERSION = "1.1.0"
DEFAULT_OUT = Path(__file__).resolve().parents[3] / "packages" / "web-contract" / "schema"


def build_one(model: type[BaseModel]) -> dict[str, Any]:
    schema = model.model_json_schema(
        by_alias=True,
        ref_template="#/$defs/{model}",
    )
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["x-contract-version"] = SCHEMA_VERSION
    schema["title"] = model.__name__
    return schema


def schema_texts() -> dict[str, str]:
    return {
        f"{name}.schema.json": json.dumps(build_one(model), ensure_ascii=False, indent=2) + "\n"
        for name, model in SCHEMA_MODELS.items()
    }


def check_schemas(out_dir: Path) -> list[str]:
    drift: list[str] = []
    for filename, content in schema_texts().items():
        path = out_dir / filename
        if not path.is_file():
            drift.append(f"missing: {path}")
        elif path.read_text(encoding="utf-8") != content:
            drift.append(f"drift: {path}")
    return drift


def write_schemas(out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for filename, content in schema_texts().items():
        path = out_dir / filename
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="fail on drift without writing")
    args = parser.parse_args(argv)
    target = args.out.resolve()
    if args.check:
        drift = check_schemas(target)
        if drift:
            for row in drift:
                print(row)
            return 1
        print(f"SCHEMA_OK {target}")
        return 0
    files = write_schemas(target)
    print(f"Exported {len(files)} JSON Schemas to {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
