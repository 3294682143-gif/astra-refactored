#!/usr/bin/env python3
"""Build deterministic TS and Python runtime views from canonical math-assets.json (U2).

Generates:
1. packages/protocol/src/generated/math-assets.ts
2. python/astra_bridge/generated/math_assets.py
Supports --check to fail if generated views drift from math-assets.json.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_JSON = ROOT / "mathagent/resources/math-assets.json"
TS_OUT = ROOT / "packages/protocol/src/generated/math-assets.ts"
PY_OUT = ROOT / "python/astra_bridge/generated/math_assets.py"


def generate_ts(catalog: dict) -> str:
    digest = hashlib.sha256(SOURCE_JSON.read_bytes()).hexdigest()
    assets = catalog["assets"]

    lines = [
        "// AUTO-GENERATED by scripts/build_math_assets.py. DO NOT EDIT DIRECTLY.",
        f'// Catalog Version: {catalog["catalogVersion"]}',
        f'// Source Digest: {digest}',
        "",
        'export const MATH_ASSET_SCHEMA_VERSION = "math-assets-v1" as const;',
        f'export const MATH_ASSET_CATALOG_VERSION = "{catalog["catalogVersion"]}" as const;',
        f'export const MATH_ASSET_CATALOG_DIGEST = "{digest}" as const;',
        "",
        "export type EvidenceCeiling =",
        '  | "EXACT_FOR_INPUT"',
        '  | "NUMERICAL_FOR_INPUT"',
        '  | "WITNESS_FOR_INPUT"',
        '  | "SAMPLED_OBSERVATION"',
        '  | "CONJECTURE"',
        '  | "GUIDANCE";',
        "",
        "export interface MathAssetBehavior {",
        "  readonly target: string;",
        "  readonly implementationRef: string;",
        "  readonly legacyToolName: string | null;",
        "  readonly legacyOperation: string | null;",
        "  readonly declaredScope: string;",
        "  readonly requiredParams: readonly string[];",
        "  readonly optionalParams: readonly string[];",
        "  readonly resultType: string;",
        "  readonly evidenceCeiling: EvidenceCeiling;",
        "  readonly consumer: string;",
        "}",
        "",
        "export interface MathAssetInstructions {",
        "  readonly conditions: readonly string[];",
        "  readonly procedure: readonly string[];",
        "  readonly misuse: readonly string[];",
        "  readonly verificationBoundary: string;",
        "}",
        "",
        "export interface MathAssetDefinition {",
        "  readonly assetId: string;",
        "  readonly name: string;",
        "  readonly version: string;",
        "  readonly summary: string;",
        "  readonly instructions: MathAssetInstructions;",
        "  readonly behaviors: readonly MathAssetBehavior[];",
        "}",
        "",
        "export const MATH_ASSETS: readonly MathAssetDefinition[] = " + json.dumps(
            [
                {
                    "assetId": a["assetId"],
                    "name": a["name"],
                    "version": a["version"],
                    "summary": a["summary"],
                    "instructions": a["instructions"],
                    "behaviors": a["behaviors"],
                }
                for a in assets
            ],
            indent=2,
            ensure_ascii=False,
        ) + " as const;",
        "",
        "export const MATH_ASSET_IDS = MATH_ASSETS.map((a) => a.assetId) as readonly string[];",
        "",
        "export const MATH_ASSET_BY_ID = new Map<string, MathAssetDefinition>(",
        "  MATH_ASSETS.map((a) => [a.assetId, a]),",
        ");",
        "",
    ]
    return "\n".join(lines)


def generate_py(catalog: dict) -> str:
    digest = hashlib.sha256(SOURCE_JSON.read_bytes()).hexdigest()
    assets = catalog["assets"]

    lines = [
        '"""AUTO-GENERATED by scripts/build_math_assets.py. DO NOT EDIT DIRECTLY."""',
        "",
        "from __future__ import annotations",
        "",
        "null = None",
        "true = True",
        "false = False",
        "",
        f'MATH_ASSET_SCHEMA_VERSION = "math-assets-v1"',
        f'MATH_ASSET_CATALOG_VERSION = "{catalog["catalogVersion"]}"',
        f'MATH_ASSET_CATALOG_DIGEST = "{digest}"',
        "",
        "MATH_ASSETS = " + json.dumps(assets, indent=4, ensure_ascii=False),
        "",
        "# Lookup from assetId to definition",
        "MATH_ASSET_BY_ID = {a['assetId']: a for a in MATH_ASSETS}",
        "MATH_ASSETS_BY_ID = MATH_ASSET_BY_ID",
        "",
        "# Lookup from (assetId, target) to behavior",
        "MATH_BEHAVIOR_LOOKUP = {}",
        "for a in MATH_ASSETS:",
        "    aid = a['assetId']",
        "    for b in a.get('behaviors', []):",
        "        MATH_BEHAVIOR_LOOKUP[(aid, b['target'])] = b",
        "",
        "__all__ = [",
        "    'MATH_ASSET_SCHEMA_VERSION',",
        "    'MATH_ASSET_CATALOG_VERSION',",
        "    'MATH_ASSET_CATALOG_DIGEST',",
        "    'MATH_ASSETS',",
        "    'MATH_ASSET_BY_ID',",
        "    'MATH_ASSETS_BY_ID',",
        "    'MATH_BEHAVIOR_LOOKUP',",
        "]",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Build or check deterministic runtime views from math-assets.json")
    parser.add_argument("--check", action="store_true", help="Check views are up to date without overwriting")
    args = parser.parse_args()

    if not SOURCE_JSON.exists():
        print(f"Error: {SOURCE_JSON} does not exist", file=sys.stderr)
        sys.exit(1)

    catalog = json.loads(SOURCE_JSON.read_text(encoding="utf-8"))
    ts_content = generate_ts(catalog)
    py_content = generate_py(catalog)

    if args.check:
        ts_ok = TS_OUT.exists() and TS_OUT.read_bytes() == ts_content.encode("utf-8")
        py_ok = PY_OUT.exists() and PY_OUT.read_bytes() == py_content.encode("utf-8")
        if not ts_ok or not py_ok:
            print(f"FAIL: Runtime views out of date (TS: {ts_ok}, PY: {py_ok}). Run without --check to regenerate.", file=sys.stderr)
            sys.exit(1)
        print("OK: Generated runtime views are synchronized and byte-identical.")
        sys.exit(0)

    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    PY_OUT.parent.mkdir(parents=True, exist_ok=True)

    TS_OUT.write_bytes(ts_content.encode("utf-8"))
    PY_OUT.write_bytes(py_content.encode("utf-8"))
    print(f"Generated {TS_OUT} ({TS_OUT.stat().st_size} bytes)")
    print(f"Generated {PY_OUT} ({PY_OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
